import console from "node:console";
import { Buffer } from "node:buffer";
import { createHash } from "node:crypto";
import { lstat, mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { basename, dirname, join, relative, resolve } from "node:path";
import process from "node:process";
import { TextDecoder } from "node:util";
import { URL, fileURLToPath, pathToFileURL } from "node:url";

const adapterRoot = fileURLToPath(new URL("../", import.meta.url));
const defaultMigrationsDirectory = join(adapterRoot, "migrations");
const defaultManifestPath = join(adapterRoot, "migration-manifest.json");
const defaultRuntimeManifestPath = join(
  adapterRoot,
  "src/generated/database-migrations.ts",
);
const migrationNamePattern =
  /^(?<version>\d{4})_[a-z0-9]+(?:_[a-z0-9]+)*\.sql$/u;
const utf8Decoder = new TextDecoder("utf-8", { fatal: true });
const utf8Bom = Buffer.from([0xef, 0xbb, 0xbf]);
const regenerateCommand =
  "pnpm --filter @one-fetch/adapter-node migrations:generate";

function sha256(bytes) {
  return createHash("sha256").update(bytes).digest("hex");
}

function displayPath(path) {
  const local = relative(adapterRoot, path);
  return local === "" || local.startsWith("..") ? path : local;
}

async function readMigrationArtifacts(migrationsDirectory) {
  const directoryEntries = (
    await readdir(migrationsDirectory, { withFileTypes: true })
  )
    .filter((entry) => entry.name.toLowerCase().endsWith(".sql"))
    .sort((left, right) =>
      left.name < right.name ? -1 : left.name > right.name ? 1 : 0,
    );
  if (directoryEntries.length === 0) {
    throw new Error(
      `No Node SQLite migrations found in ${displayPath(migrationsDirectory)}`,
    );
  }

  const artifacts = [];
  for (const [index, directoryEntry] of directoryEntries.entries()) {
    if (!directoryEntry.isFile() || directoryEntry.isSymbolicLink()) {
      throw new Error(
        `Migration must be a regular file: ${directoryEntry.name}`,
      );
    }
    const name = migrationNamePattern.exec(directoryEntry.name);
    if (!name?.groups) {
      throw new Error(
        `Invalid migration name "${directoryEntry.name}"; expected NNNN_lowercase_name.sql`,
      );
    }
    const version = Number(name.groups.version);
    if (version !== index + 1) {
      throw new Error(
        `Migration versions must be contiguous: expected ${String(index + 1).padStart(4, "0")}, found ${name.groups.version}`,
      );
    }

    const path = join(migrationsDirectory, directoryEntry.name);
    const beforeRead = await lstat(path);
    const bytes = await readFile(path);
    const afterRead = await lstat(path);
    if (
      !beforeRead.isFile() ||
      beforeRead.isSymbolicLink() ||
      beforeRead.size !== afterRead.size ||
      beforeRead.mtimeMs !== afterRead.mtimeMs
    ) {
      throw new Error(
        `Migration changed while being read: ${directoryEntry.name}`,
      );
    }
    if (bytes.subarray(0, utf8Bom.length).equals(utf8Bom)) {
      throw new Error(
        `Migration must not contain a UTF-8 BOM: ${directoryEntry.name}`,
      );
    }
    let sql;
    try {
      sql = utf8Decoder.decode(bytes);
    } catch (error) {
      throw new Error(`Migration is not valid UTF-8: ${directoryEntry.name}`, {
        cause: error,
      });
    }
    if (!sql.trim()) {
      throw new Error(`Migration must contain SQL: ${directoryEntry.name}`);
    }
    artifacts.push({
      version,
      file: directoryEntry.name,
      bytes: bytes.byteLength,
      artifactSha256: sha256(bytes),
      sql,
    });
  }
  return artifacts;
}

function createManifest(artifacts, migrationsDirectory) {
  return {
    schemaVersion: 1,
    hashAlgorithm: "sha256",
    migrationsDirectory: basename(migrationsDirectory),
    migrations: artifacts.map(({ version, file, bytes, artifactSha256 }) => ({
      version,
      file,
      bytes,
      artifactSha256,
    })),
  };
}

export async function buildMigrationArtifacts({
  migrationsDirectory = defaultMigrationsDirectory,
} = {}) {
  const migrations = await readMigrationArtifacts(migrationsDirectory);
  return {
    manifest: createManifest(migrations, migrationsDirectory),
    migrations,
  };
}

export function renderMigrationManifest(manifest) {
  return `${JSON.stringify(manifest, null, 2)}\n`;
}

export function renderRuntimeMigrations(migrations) {
  const rows = migrations
    .map(
      (migration) => `  {
    version: ${migration.version},
    file: ${JSON.stringify(migration.file)},
    bytes: ${migration.bytes},
    artifactSha256:
      ${JSON.stringify(migration.artifactSha256)},
    sql: ${JSON.stringify(migration.sql)},
  },`,
    )
    .join("\n");
  return `/* Generated by scripts/migration-integrity.mjs. Do not edit. */
export const NODE_DATABASE_SCHEMA_VERSION = ${migrations.length} as const;

export const NODE_DATABASE_MIGRATIONS = [
${rows}
] as const;
`;
}

async function readJson(path) {
  try {
    const text = await readFile(path, "utf8");
    return { text, value: JSON.parse(text) };
  } catch (error) {
    if (error && typeof error === "object" && error.code === "ENOENT") {
      return null;
    }
    throw error;
  }
}

function previousMigrationRows(previous) {
  if (!previous) return [];
  const value = previous.value;
  if (
    !value ||
    typeof value !== "object" ||
    value.schemaVersion !== 1 ||
    value.hashAlgorithm !== "sha256" ||
    !Array.isArray(value.migrations)
  ) {
    throw new Error("Existing Node migration manifest is invalid");
  }
  return value.migrations;
}

function assertAppendOnly(previous, current) {
  const previousRows = previousMigrationRows(previous);
  if (previousRows.length > current.length) {
    throw new Error("Recorded Node migrations must not be deleted");
  }
  for (const [index, previousRow] of previousRows.entries()) {
    const currentRow = current[index];
    if (
      !currentRow ||
      previousRow.version !== currentRow.version ||
      previousRow.file !== currentRow.file ||
      previousRow.bytes !== currentRow.bytes ||
      previousRow.artifactSha256 !== currentRow.artifactSha256
    ) {
      throw new Error(
        `Recorded Node migration is immutable: ${previousRow.file ?? index + 1}`,
      );
    }
  }
}

async function assertRegularOutput(path) {
  try {
    const stat = await lstat(path);
    if (!stat.isFile() || stat.isSymbolicLink()) {
      throw new Error(
        `Generated output must be a regular file: ${displayPath(path)}`,
      );
    }
  } catch (error) {
    if (!error || typeof error !== "object" || error.code !== "ENOENT") {
      throw error;
    }
  }
}

export async function verifyMigrationArtifacts({
  migrationsDirectory = defaultMigrationsDirectory,
  manifestPath = defaultManifestPath,
  runtimeManifestPath = defaultRuntimeManifestPath,
} = {}) {
  const expected = await buildMigrationArtifacts({ migrationsDirectory });
  const actualManifest = await readJson(manifestPath);
  if (
    !actualManifest ||
    actualManifest.text !== renderMigrationManifest(expected.manifest)
  ) {
    throw new Error(
      `Node migration manifest is missing or stale. Run "${regenerateCommand}".`,
    );
  }
  let runtimeText;
  try {
    runtimeText = await readFile(runtimeManifestPath, "utf8");
  } catch (error) {
    if (error && typeof error === "object" && error.code === "ENOENT") {
      throw new Error(
        `Generated Node migrations are missing. Run "${regenerateCommand}".`,
      );
    }
    throw error;
  }
  if (runtimeText !== renderRuntimeMigrations(expected.migrations)) {
    throw new Error(
      `Generated Node migrations are stale. Run "${regenerateCommand}".`,
    );
  }
  return expected.manifest;
}

export async function writeMigrationArtifacts({
  migrationsDirectory = defaultMigrationsDirectory,
  manifestPath = defaultManifestPath,
  runtimeManifestPath = defaultRuntimeManifestPath,
} = {}) {
  await assertRegularOutput(manifestPath);
  await assertRegularOutput(runtimeManifestPath);
  const previous = await readJson(manifestPath);
  const artifacts = await buildMigrationArtifacts({ migrationsDirectory });
  assertAppendOnly(previous, artifacts.manifest.migrations);
  await mkdir(dirname(runtimeManifestPath), { recursive: true });
  await writeFile(
    manifestPath,
    renderMigrationManifest(artifacts.manifest),
    "utf8",
  );
  await writeFile(
    runtimeManifestPath,
    renderRuntimeMigrations(artifacts.migrations),
    "utf8",
  );
  return artifacts.manifest;
}

async function main() {
  const args = process.argv.slice(2);
  const mode = args.length === 0 ? "--check" : args[0];
  if (args.length > 1 || (mode !== "--check" && mode !== "--write")) {
    throw new Error(
      "Usage: node scripts/migration-integrity.mjs [--check|--write]",
    );
  }
  const manifest =
    mode === "--write"
      ? await writeMigrationArtifacts()
      : await verifyMigrationArtifacts();
  console.log(
    `${mode === "--write" ? "Wrote" : "Verified"} ${manifest.migrations.length} Node SQLite migrations`,
  );
}

const invokedPath = process.argv[1]
  ? pathToFileURL(resolve(process.argv[1])).href
  : "";
if (import.meta.url === invokedPath) {
  main().catch((error) => {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  });
}
